"""Arithmetic in GF(2^m) (private).

:class:`_Field` holds the log and antilog tables of one field (built on the
host from a primitive polynomial) and does elementwise arithmetic on
integer arrays of either device by table gathers, plus the GF(2)-linear
view of the field: multiplication by a constant is an ``m x m`` binary
matrix on the bits of an element (MSB first), so evaluating polynomials
at many fixed points is one :func:`~commkit.coding._gf2.matmul_mod2`.
Used by the BCH and Reed-Solomon codes of :mod:`commkit.coding.algebraic`.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import cached_property
from typing import Any

import numpy as np

from ..backend import ArrayType, _device_tables, get_array_module
from ..mapping.gray import _unpack_bits

# Primitive polynomials (with the x^m term), the common choice per degree:
# x^8 + x^4 + x^3 + x^2 + 1 is the one of ITU-T G.709 and the IEEE 802.3
# RS codes over GF(2^8); x^10 + x^3 + 1 that of IEEE 802.3 clause 91.
PRIMITIVE = {
    3: 0xB,
    4: 0x13,
    5: 0x25,
    6: 0x43,
    7: 0x89,
    8: 0x11D,
    9: 0x211,
    10: 0x409,
    11: 0x805,
    12: 0x1053,
    13: 0x201B,
    14: 0x4443,
    15: 0x8003,
    16: 0x1100B,
}


@dataclass(frozen=True)
class _Field:
    """GF(2^m) generated by a primitive polynomial (with its ``x^m`` term)."""

    m: int
    primitive: int

    def __post_init__(self) -> None:
        if not 2 <= self.m <= 16:
            raise ValueError(f"m must be in [2, 16], got {self.m}.")
        if self.primitive >> self.m != 1:
            raise ValueError(
                f"primitive polynomial 0x{self.primitive:X} is not of degree {self.m}."
            )
        exp = self._tables[0]
        if np.unique(exp[: self.order - 1]).size != self.order - 1:
            raise ValueError(f"0x{self.primitive:X} is not primitive over GF(2).")

    @property
    def order(self) -> int:
        """Number of elements ``q = 2^m``."""
        return 1 << self.m

    @cached_property
    def _tables(self) -> tuple[np.ndarray, np.ndarray]:
        """``(exp, log)``: ``exp`` ``(2q,)`` (doubled, no reduction of sums
        of two logs), ``log`` ``(q,)`` with ``log[0] = 0`` (masked by users)."""
        q = self.order
        exp = np.zeros(2 * q, dtype=np.int64)
        v = 1
        for i in range(q - 1):
            exp[i] = v
            v <<= 1
            if v & q:
                v ^= self.primitive
        exp[q - 1 : 2 * q - 2] = exp[: q - 1]
        log = np.zeros(q, dtype=np.int64)
        log[exp[: q - 1]] = np.arange(q - 1)
        return exp, log

    # -- host scalars --------------------------------------------------------

    def alpha(self, power: int) -> int:
        """``alpha^power`` (any integer power)."""
        return int(self._tables[0][power % (self.order - 1)])

    def mul_scalar(self, a: int, b: int) -> int:
        """Product of two host elements."""
        if a == 0 or b == 0:
            return 0
        exp, log = self._tables
        return int(exp[log[a] + log[b]])

    # -- arrays on either device ---------------------------------------------

    def tables(self, xp: Any) -> tuple[ArrayType, ArrayType]:
        """The ``(exp, log)`` tables on ``xp``'s device."""
        exp, log = _device_tables(self, "gf", xp, lambda: self._tables)
        return exp, log

    def mul(self, a: ArrayType, b: ArrayType) -> ArrayType:
        """Elementwise product of field elements (int arrays, broadcast)."""
        xp = get_array_module(a)
        exp, log = self.tables(xp)
        return xp.where((a == 0) | (b == 0), 0, exp[log[a] + log[b]])

    def div(self, a: ArrayType, b: ArrayType) -> ArrayType:
        """Elementwise ``a / b``; zero where ``a`` or ``b`` is zero."""
        xp = get_array_module(a)
        exp, log = self.tables(xp)
        q1 = self.order - 1
        return xp.where((a == 0) | (b == 0), 0, exp[log[a] - log[b] + q1])

    # -- the GF(2)-linear view -------------------------------------------------

    def bits(self, values: Any) -> np.ndarray:
        """Host elements to their ``m`` bits, MSB first: ``(..., m)`` int8."""
        v = np.asarray(values, dtype=np.int64)
        return _unpack_bits(v.reshape(-1), self.m).reshape(*v.shape, self.m)

    def evaluation_matrix(self, powers: np.ndarray) -> np.ndarray:
        """Bits of ``sum_j a_j beta_i^j`` from the bits of ``a_0 .. a_{d-1}``.

        ``powers`` is ``(d, n)``: the exponent of ``alpha`` that multiplies
        coefficient ``j`` at point ``i``.  Returns int8 ``(d m, n m)``: row
        ``(j, r)`` holds the bits of ``2^(m-1-r) alpha^powers[j, i]`` for
        every point, so ``coefficient bits @ matrix`` (mod 2) gives the bits
        of the ``n`` values.
        """
        exp, log = self._tables
        q1 = self.order - 1
        basis = 1 << np.arange(self.m - 1, -1, -1)  # elements of bit r, MSB first
        idx = (log[basis][None, :, None] + np.asarray(powers)[:, None, :]) % q1
        products = exp[idx]  # (d, m, n)
        d, n = products.shape[0], products.shape[2]
        return self.bits(products).reshape(d * self.m, n * self.m)
